<?php

namespace App\Shell\Console\Commands;

use Illuminate\Console\Command;

class ProxyConfigCommand extends Command
{
    protected $signature = 'ghar:proxy-config {path=/run/nginx/real-ip.conf : Where to write the nginx snippet}';

    protected $description = 'Write the nginx real-IP snippet for TRUSTED_PROXIES (run by the container entrypoint)';

    public function handle(): int
    {
        /** @var list<string>|'*' $proxies */
        $proxies = config('trustedproxy.proxies');

        $snippet = "# Generated by ghar:proxy-config from TRUSTED_PROXIES. Do not edit.\n";

        // Behind Cloudflare a local proxy (Traefik, Caddy) often rewrites X-Forwarded-For to the
        // edge's address, so the client IP has to come from the header Cloudflare sets itself.
        if (config('trustedproxy.cloudflare') === true && is_array($proxies)) {
            $snippet .= "real_ip_header CF-Connecting-IP;\nreal_ip_recursive on;\n";
            foreach ($proxies as $range) {
                $snippet .= "set_real_ip_from {$range};\n";
            }
        }

        if (@file_put_contents((string) $this->argument('path'), $snippet) === false) {
            $this->error("Could not write {$this->argument('path')}.");

            return self::FAILURE;
        }

        $this->line('Trusted proxies: '.(is_array($proxies) ? implode(', ', $proxies) : 'all (*)'));

        return self::SUCCESS;
    }
}
